  findConfigSeparator(line) {
    let bracketLevel = 0;
    let parenLevel = 0;
    for (let i = 0; i < line.length; i++) {
      const char = line[i];
      if (char === "[")
        bracketLevel++;
      else if (char === "]")
        bracketLevel--;
      else if (char === "(")
        parenLevel++;
      else if (char === ")")
        parenLevel--;
      else if (char === "," && bracketLevel === 0 && parenLevel === 0) {
        return i;
      }
    }
    return -1;
  }
