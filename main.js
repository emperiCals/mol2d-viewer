    let lastIdx = 0;
    for (let i = 0; i < str.length; i++) {
      const c = str[i];
      if (c === "[")
        bracketLevel++;
      else if (c === "]")
        bracketLevel--;
      else if (c === "+" && bracketLevel === 0) {
        parts.push(str.substring(lastIdx, i).trim());
        lastIdx = i + 1;
      }
    }
    parts.push(str.substring(lastIdx).trim());
    return parts.filter((p) => p);
